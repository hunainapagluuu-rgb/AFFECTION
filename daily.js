// LOGIC: picks today's content and plugs it into the existing sections.
// Nothing below needs editing, except START.
// =====================================================================
(function () {
  // Day 1 = this date (year, month, day). Month is 0-based: 0 = Jan ... 9 = Oct.
  var START = new Date(2026, 9, 11);

  // Preview other days by opening the site with ?day=0, ?day=1, ?day=50 ...
  var preview = new URLSearchParams(location.search).get('day');
  var now = new Date();
  var elapsed = Math.floor(
    (Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) -
      Date.UTC(START.getFullYear(), START.getMonth(), START.getDate())) / 864e5
  );
  var dayIndex = Math.max(0, preview !== null ? (Number(preview) || 0) : elapsed);

  var C = window.DAILY_CONTENT;
  function pick(list) { return list[dayIndex % list.length]; }

  // ---------- small style block (inherits the site's fonts and colours) ----------
  var css = document.createElement('style');
  css.textContent =
    '.daily-wrap{margin:1.2rem auto;max-width:640px;text-align:left}' +
    '.daily-btn{display:block;width:100%;margin:.6rem 0 0;padding:.85rem 1.1rem;text-align:left;cursor:pointer;' +
    'font:inherit;color:inherit;background:transparent;border:1px solid currentColor;border-color:rgba(128,128,128,.45);border-radius:14px}' +
    '.daily-btn small{opacity:.6;margin-left:.5rem;font-size:.8em}' +
    '.daily-btn:hover{background:rgba(128,128,128,.08)}' +
    '.daily-text{margin:.5rem .2rem 0;padding:.2rem .4rem;line-height:1.7;font:inherit}' +
    '.daily-text[hidden]{display:none}' +
    '.daily-msg{margin:1.2rem auto 0;max-width:640px;line-height:1.8;font:inherit;font-style:italic;text-align:center}';
  document.head.appendChild(css);

  // ---------- helpers ----------
  function looksLikeOpener(el) {
    return /tap to open/i.test(el.textContent || '');
  }
  function smallest(els) {
    // keep only the innermost elements (drop any element that contains another match)
    return els.filter(function (a) {
      return !els.some(function (b) { return b !== a && a.contains(b); });
    });
  }
  function commonParent(els) {
    var p = els[0].parentElement;
    while (p && !els.every(function (e) { return p.contains(e); })) p = p.parentElement;
    return p;
  }

  // =================== LITTLE THINGS ===================
  var doneLT = false;
  function initLittleThings() {
    var sec = document.getElementById('little-things');
    if (!sec || doneLT) return !!doneLT;

    // find the existing 3 "tap to open" items
    var cands = Array.prototype.slice.call(
      sec.querySelectorAll('button, summary, details, [role="button"], li, div, p, a')
    ).filter(looksLikeOpener);
    cands = smallest(cands);
    // climb each match to the whole clickable item (button / details / summary)
    var items = cands.map(function (el) {
      return el.closest('button, details, [role="button"]') || el;
    });
    items = items.filter(function (el, i) { return items.indexOf(el) === i; });

    var anchorAfter = null;
    if (items.length) {
      var parent = commonParent(items);
      if (parent && parent !== sec && items.length >= 2) {
        parent.style.display = 'none';
        anchorAfter = parent;
      } else {
        items.forEach(function (el) { el.style.display = 'none'; });
        anchorAfter = items[items.length - 1];
      }
    }

    var wrap = document.createElement('div');
    wrap.className = 'daily-wrap';
    var icons = ['\u2727', '\u2661', '\u263E'];
    [C.comfort, C.admire, C.light].forEach(function (list, i) {
      var n = pick(list);
      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'daily-btn';
      btn.setAttribute('aria-expanded', 'false');
      btn.innerHTML = icons[i] + ' ' + n[0].replace(/</g, '&lt;') + '<small>tap to open</small>';
      var p = document.createElement('p');
      p.className = 'daily-text';
      p.hidden = true;
      p.textContent = n[1];
      btn.addEventListener('click', function () {
        p.hidden = !p.hidden;
        btn.setAttribute('aria-expanded', String(!p.hidden));
      });
      wrap.appendChild(btn);
      wrap.appendChild(p);
    });

    if (anchorAfter && anchorAfter.parentNode) {
      anchorAfter.parentNode.insertBefore(wrap, anchorAfter.nextSibling);
    } else {
      sec.appendChild(wrap);
    }
    doneLT = true;
    return true;
  }

  // =================== 3 AM ===================
  var doneAM = false;
  function initThreeAm() {
    var sec = document.getElementById('three-am');
    if (!sec || doneAM) return !!doneAM;

    var moods = [
      { re: /miss/i, list: C.miss },
      { re: /comfort/i, list: C.comfortNight },
      { re: /close/i, list: C.close }
    ];
    var buttons = Array.prototype.slice.call(sec.querySelectorAll('button, [role="button"]'));
    var choiceBtns = buttons.filter(function (b) {
      return moods.some(function (m) { return m.re.test(b.textContent || ''); });
    });
    if (!choiceBtns.length) return false;

    var holder = commonParent(choiceBtns) || sec;
    var msg = document.createElement('p');
    msg.className = 'daily-msg';
    msg.setAttribute('aria-live', 'polite');
    holder.parentNode.insertBefore(msg, holder.nextSibling);

    // capture phase: our message replaces whatever the old buttons used to show
    sec.addEventListener('click', function (e) {
      var b = e.target.closest ? e.target.closest('button, [role="button"]') : null;
      if (!b || choiceBtns.indexOf(b) === -1) return;
      var text = b.textContent || '';
      var mood = moods.filter(function (m) { return m.re.test(text); })[0];
      if (!mood) return;
      e.stopPropagation();
      e.preventDefault();
      msg.textContent = pick(mood.list);
    }, true);

    doneAM = true;
    return true;
  }

  // =================== start (also waits if the page builds itself late) ===================
  function tryInit() { initLittleThings(); initThreeAm(); return doneLT && doneAM; }
  function start() {
    if (tryInit()) return;
    var tries = 0;
    var obs = new MutationObserver(function () {
      if (tryInit() || ++tries > 200) obs.disconnect();
    });
    obs.observe(document.documentElement, { childList: true, subtree: true });
    setTimeout(function () { obs.disconnect(); }, 15000);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
  else start();
})();
